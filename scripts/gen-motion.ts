/**
 * Generates packages/m3/src/tokens/motion.stylex.ts and motion-themes.ts
 * from the spring tokens. StyleX needs literal values, so the exact
 * spring → CSS linear() conversion happens here, not at runtime.
 *
 *   pnpm gen:motion
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settleTimeMs, springToLinear } from '../packages/m3/src/motion/spring.ts';
import { motionSchemes, type SpringToken } from '../packages/m3/src/motion/tokens.ts';

const tokensDir = fileURLToPath(new URL('../packages/m3/src/tokens/', import.meta.url));
const header = '// GENERATED by scripts/gen-motion.ts from motion/tokens.ts — do not edit.\n';
const REDUCED = '@media (prefers-reduced-motion: reduce)';

const camel = (token: SpringToken) =>
  token.replace(/-(\w)/g, (_, c: string) => c.toUpperCase()) as string;

function entries(scheme: keyof typeof motionSchemes) {
  const out: string[] = [];
  for (const [token, spring] of Object.entries(motionSchemes[scheme]) as Array<
    [SpringToken, (typeof motionSchemes)['expressive'][SpringToken]]
  >) {
    const name = camel(token);
    const duration = `${settleTimeMs(spring)}ms`;
    const easing = springToLinear(spring);
    const spatial = token.endsWith('spatial');
    // Reduced motion: movement becomes instant; colour/opacity fades stay.
    const d = spatial ? `{ default: '${duration}', '${REDUCED}': '0ms' }` : `'${duration}'`;
    out.push(`  /** ${token}: dampingRatio ${spring.dampingRatio}, stiffness ${spring.stiffness} */`);
    out.push(`  ${name}Duration: ${d},`);
    out.push(`  ${name}Easing: '${easing}',`);
  }
  return out.join('\n');
}

writeFileSync(
  `${tokensDir}motion.stylex.ts`,
  `${header}import * as stylex from '@stylexjs/stylex';

/**
 * md.sys.motion.spring.* as CSS. Defaults to the expressive scheme; apply
 * \`standardMotionTheme\` (motion-themes.ts) to a subtree to swap schemes,
 * mirroring Compose's LocalMotionScheme.
 *
 * Use with transitions: \`transition: \${prop} \${motion.fastSpatialDuration} \${motion.fastSpatialEasing}\`.
 */
export const motion = stylex.defineVars({
${entries('expressive')}
});
`,
);

writeFileSync(
  `${tokensDir}motion-themes.ts`,
  `${header}import * as stylex from '@stylexjs/stylex';
import { motion } from './motion.stylex';

export const expressiveMotionTheme = stylex.createTheme(motion, {
${entries('expressive')}
});

export const standardMotionTheme = stylex.createTheme(motion, {
${entries('standard')}
});
`,
);

console.log('motion tokens written to', tokensDir);
