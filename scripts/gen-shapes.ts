/**
 * Figma Shape Set SVG → packages/m3/src/shapes/figmaPaths.ts
 *
 *   pnpm gen:shapes
 *
 * Takes each `<g id="Shape=…">` path from the whole-set SVG export
 * (figma/shapes/_frames/shape-set.svg), translates it from set coordinates into
 * its component's local 380×380 frame (offsets from figma/shapes/manifest.json),
 * and emits exact path data. These are the static shapes: pixel-identical to the
 * kit by construction.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Manifest } from '../tests/visual/manifest.ts';

const root = new URL('../', import.meta.url);
const read = (p: string) => readFileSync(fileURLToPath(new URL(p, root)), 'utf8');

/** Translate an absolute-command SVG path (M L H V C Q Z — what Figma exports). */
export function translatePath(d: string, dx: number, dy: number): string {
  const tokens = d.match(/[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/g) ?? [];
  const out: string[] = [];
  let cmd = '';
  let argIndex = 0;
  const fmt = (n: number) => String(Math.round(n * 10000) / 10000);
  for (const t of tokens) {
    if (/^[A-Za-z]$/.test(t)) {
      if (t !== t.toUpperCase() && t !== 'z') throw new Error(`relative command "${t}" not supported`);
      if (!'MLHVCQZz'.includes(t)) throw new Error(`command "${t}" not supported`);
      cmd = t.toUpperCase();
      argIndex = 0;
      out.push(cmd);
      continue;
    }
    const n = Number(t);
    let v: number;
    if (cmd === 'H') v = n - dx;
    else if (cmd === 'V') v = n - dy;
    else v = argIndex % 2 === 0 ? n - dx : n - dy;
    argIndex++;
    out.push(fmt(v));
  }
  return out.join(' ').replace(/ ?([MLHVCQZ]) ?/g, '$1');
}

const camel = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

export function render(svg: string, manifest: Manifest): string {
  const rows: string[] = [];
  for (const [key, v] of Object.entries(manifest.variants) as Array<
    [string, Manifest['variants'][string] & { figmaName?: string }]
  >) {
    const id = v.figmaName!;
    const group = svg.match(new RegExp(`<g id="${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}">([\\s\\S]*?)</g>`));
    if (!group) throw new Error(`group ${id} not found in SVG`);
    const path = group[1]!.match(/<path[^>]*\sd="([^"]+)"[^>]*>/);
    if (!path) throw new Error(`no path in ${id}`);
    const fillRule = /fill-rule="evenodd"/.test(path[0]) ? 'evenodd' : 'nonzero';
    const d = translatePath(path[1]!, v.crop!.x, v.crop!.y);
    const box = v.layers!.find((l) => l.name === 'shape')!.box;
    rows.push(
      `  /** Figma "${id}" (${v.node}) */\n  ${camel(key)}: { d: '${d}', fillRule: '${fillRule}', box: [${box.join(', ')}] },`,
    );
  }
  return `// GENERATED by scripts/gen-shapes.ts from figma/shapes/_frames/shape-set.svg — do not edit.

/** Every shape component in the kit is a 380×380 frame. */
export const SHAPE_FRAME = 380;

/**
 * M3 Expressive shape set, exact Figma geometry in frame coordinates.
 * \`box\` is the vector's bounds inside the frame [x, y, w, h].
 */
export const figmaShapes = {
${rows.join('\n')}
} as const satisfies Record<string, { d: string; fillRule: 'nonzero' | 'evenodd'; box: readonly number[] }>;

export type ShapeName = keyof typeof figmaShapes;
`;
}

export const loadInputs = () => ({
  svg: read('figma/shapes/_frames/shape-set.svg'),
  manifest: JSON.parse(read('figma/shapes/manifest.json')) as Manifest,
});
export const outPath = fileURLToPath(new URL('packages/m3/src/shapes/figmaPaths.ts', root));

if (import.meta.url === `file://${process.argv[1]}`) {
  const { svg, manifest } = loadInputs();
  writeFileSync(outPath, render(svg, manifest));
  console.log('shapes written to', outPath);
}
